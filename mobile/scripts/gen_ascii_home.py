#!/usr/bin/env python3
"""Precompute the Home ASCII scene from assets/mock/poster.jpg.

    python3 scripts/gen_ascii_home.py [--preview out.png]

Writes src/ascii/homeScene.ts: glyph rows (luminance ramp), a warm-only layer (lit windows, lamps),
three glow layers (subsets of the brightest cells, animated by AsciiScene) and per-cell levels 0-9.
"""
import argparse, colorsys, os, random
from PIL import Image, ImageEnhance, ImageFilter, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAMP = " .:-=+*#%@"
COLS = 72
CELL_ASPECT = 0.6  # JetBrains Mono advance / line height
GLOW_LAYERS = 3
GLOW_CELLS = 420

img = Image.open(os.path.join(ROOT, "assets/mock/poster.jpg")).convert("RGB")
rows_n = round(COLS * img.height / img.width * CELL_ASPECT)
small = img.resize((COLS, rows_n), Image.LANCZOS)
small = small.filter(ImageFilter.UnsharpMask(radius=1, percent=120))
lums = sorted(0.2126 * r + 0.7152 * g + 0.0722 * b for r, g, b in small.getdata())
lo, hi = lums[int(len(lums) * 0.04)] / 255, lums[int(len(lums) * 0.995)] / 255
px = small.load()

rows, warm, level = [], [], []
cells = []
for y in range(rows_n):
    r_s, w_s, l_s = "", "", ""
    for x in range(COLS):
        r, g, b = (c / 255 for c in px[x, y])
        lum = 0.2126 * r + 0.7152 * g + 0.0722 * b
        lum = min(1.0, max(0.0, (lum - lo) / (hi - lo))) ** 0.6
        i = min(len(RAMP) - 1, int(lum * len(RAMP)))
        h, s, v = colorsys.rgb_to_hsv(r, g, b)
        is_warm = i >= 2 and s > 0.2 and (h < 0.17 or h > 0.96)
        r_s += RAMP[i]
        w_s += RAMP[i] if is_warm else " "
        l_s += str(i)
        if is_warm and i >= 4 or i >= 8:
            cells.append((y, x))
    rows.append(r_s)
    warm.append(w_s)
    level.append(l_s)

random.seed(7)
random.shuffle(cells)
cells = cells[:GLOW_CELLS]
glow = [[[" "] * COLS for _ in range(rows_n)] for _ in range(GLOW_LAYERS)]
for n, (y, x) in enumerate(cells):
    glow[n % GLOW_LAYERS][y][x] = rows[y][x]
glow = [["".join(r) for r in layer] for layer in glow]

def lit(name, data):
    body = ",\n".join('    "%s"' % r.replace("\\", "\\\\").replace('"', '\\"') for r in data)
    return "  %s: [\n%s,\n  ]" % (name, body)

out = "// Generated by scripts/gen_ascii_home.py from assets/mock/poster.jpg. Do not edit by hand.\n"
out += "export const homeScene = {\n  cols: %d,\n  rowCount: %d,\n" % (COLS, rows_n)
out += lit("rows", rows) + ",\n" + lit("warm", warm) + ",\n" + lit("level", level) + ",\n"
out += "  glow: [\n" + ",\n".join("  " + lit("", g).strip()[3:].rstrip() if False else "    [\n" + ",\n".join('      "%s"' % r.replace("\\", "\\\\").replace('"', '\\"') for r in g) + ",\n    ]" for g in glow) + ",\n  ],\n};\n"
os.makedirs(os.path.join(ROOT, "src/ascii"), exist_ok=True)
open(os.path.join(ROOT, "src/ascii/homeScene.ts"), "w").write(out)
print("wrote src/ascii/homeScene.ts", COLS, "x", rows_n, "glow cells", len(cells))

ap = argparse.ArgumentParser()
ap.add_argument("--preview")
a = ap.parse_args()
if a.preview:
    fs = 16
    font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf", fs)
    cw = font.getlength("M")
    im = Image.new("RGB", (int(COLS * cw) + 20, rows_n * fs + 20), "#0C0A08")
    d = ImageDraw.Draw(im)
    for y in range(rows_n):
        for x in range(COLS):
            ch = rows[y][x]
            if ch == " ":
                continue
            lv = int(level[y][x]) / 9
            if warm[y][x] != " ":
                col = tuple(int(c * (0.45 + 0.55 * lv)) for c in (245, 164, 66))
            else:
                col = tuple(int(c * (0.3 + 0.7 * lv)) for c in (200, 205, 212))
            d.text((10 + x * cw, 10 + y * fs), ch, font=font, fill=col)
    for layer in glow:
        for y, row in enumerate(layer):
            for x, ch in enumerate(row):
                if ch != " ":
                    d.text((10 + x * cw, 10 + y * fs), ch, font=font, fill=(255, 233, 185))
    im.save(os.path.expanduser(a.preview))
