import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "assets/world");
const read = (p) => readFileSync(join(dist, p));
let html = read("index.html").toString("utf8");

html = html.replace(/<link rel="stylesheet"[^>]*href="\.\/([^"]+)"[^>]*>/, (_, href) => {
  const css = read(href)
    .toString("utf8")
    .replace(/url\(\.?\/?(?:assets\/)?([^)"']+\.woff2)\)/g, (__, file) => `url(data:font/woff2;base64,${read(`assets/${file}`).toString("base64")})`);
  return `<style>${css}</style>`;
});

let script = "";
html = html.replace(/\s*<script type="module"[^>]*src="\.\/([^"]+)"[^>]*><\/script>/, (_, src) => {
  script = read(src).toString("utf8").replace(/<\/script/gi, "<\\/script");
  return "";
});
if (!script) throw new Error("module script not found in world build");
html = html.replace("</body>", () => `<script type="module">${script}</script></body>`);

const out = `// Generated by scripts/sync-world.sh. Do not edit.\nexport const worldHtml = ${JSON.stringify(html)};\n`;
writeFileSync(join(root, "src/world/worldHtml.ts"), out);
console.log(`worldHtml.ts: ${(out.length / 1024).toFixed(0)} kB`);
